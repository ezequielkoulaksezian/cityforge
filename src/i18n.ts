export type TKey = keyof typeof es;
const dicts: Record<Lang, Dict> = { es, en };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("cityforge.lang");
    if (saved === "es" || saved === "en") return saved;
  } catch {}
  return navigator.language?.toLowerCase().startsWith("es") ? "es" : "en";
}

export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? key;
  if (params)
    for (const [k, v] of Object.entries(params)) {
      const value = typeof v === "number" ? v.toLocaleString(lang === "es" ? "es-AR" : "en-US") : v;
      s = s.replace(`{${k}}`, value).replace(`\${${k}}`, `$${value}`);
    }
  return s;
}
